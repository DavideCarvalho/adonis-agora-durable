import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { IndexGenerator } from '@adonisjs/assembler/index_generator';
import type { ApplicationService } from '@adonisjs/core/types';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import DurableProvider from '../../providers/durable_provider.js';
import type { DurableConfig } from '../../src/define_config.js';
import { WorkflowEngine } from '../../src/engine.js';
import defaultStepsHook, { stepsHook } from '../../src/hooks/steps.js';
import defaultWorkflowsHook, { workflowsHook } from '../../src/hooks/workflows.js';

const SRC = fileURLToPath(new URL('../../src', import.meta.url));
const silent = { info() {} } as never;

let appRoot: string;
const write = async (rel: string, contents: string) => {
  const file = join(appRoot, rel);
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, contents);
  return file;
};
const read = (rel: string) => readFile(join(appRoot, rel), 'utf8');

beforeEach(async () => {
  appRoot = await mkdtemp(join(tmpdir(), 'durable-hooks-'));
});
afterEach(async () => {
  await rm(appRoot, { recursive: true, force: true });
});

function generator() {
  return new IndexGenerator(appRoot, silent);
}

describe('single-root barrels are unchanged', () => {
  it('writes the exact historical workflows barrel (nested sub-directory included)', async () => {
    await write('app/workflows/charge_workflow.ts', 'export default 1');
    await write('app/workflows/billing/refund_workflow.ts', 'export default 1');
    const gen = generator();
    defaultWorkflowsHook(undefined, undefined, gen);
    await gen.generate();

    // Captured from the pre-multi-root hook: the one-directory output must not move a byte.
    expect(await read('.adonisjs/durable/workflows.ts')).toBe(
      `/**
 * This file is automatically generated.
 * DO NOT EDIT manually
 */

export const workflows = {
  billing: {
    Refund: () => import('#workflows/billing/refund_workflow'),
  },
  Charge: () => import('#workflows/charge_workflow'),
}
`,
    );
  });

  it('a one-element source array is the single-root barrel', async () => {
    await write('app/steps/charge_step.ts', 'export default 1');
    const a = generator();
    defaultStepsHook(undefined, undefined, a);
    await a.generate();
    const single = await read('.adonisjs/durable/steps.ts');

    const b = generator();
    stepsHook({ source: ['app/steps'] })(undefined, undefined, b);
    await b.generate();
    expect(await read('.adonisjs/durable/steps.ts')).toBe(single);
  });
});

describe('multi-root barrels', () => {
  it('writes ONE barrel covering every root, importing through relative paths', async () => {
    await write('app/orders/flows/place_workflow.ts', 'export default 1');
    await write('app/billing/flows/charge_workflow.ts', 'export default 1');
    // A built twin next to its source is one module, keyed by the .ts file.
    await write('app/billing/flows/charge_workflow.js', 'export default 1');
    const gen = generator();
    workflowsHook({ source: ['app/orders/flows', 'app/billing/flows'] })(undefined, undefined, gen);
    await gen.generate();

    expect(await read('.adonisjs/durable/workflows.ts')).toBe(
      `/**
 * This file is automatically generated.
 * DO NOT EDIT manually
 */

export const workflows = [
  {
    root: 'app/orders/flows',
    modules: {
      'app/orders/flows/place_workflow.ts': () => import('../../app/orders/flows/place_workflow.js'),
    },
  },
  {
    root: 'app/billing/flows',
    modules: {
      'app/billing/flows/charge_workflow.ts': () => import('../../app/billing/flows/charge_workflow.js'),
    },
  },
]
`,
    );
  });

  it('the watcher regenerates the barrel on a change in ANY root', async () => {
    await write('app/a/steps/one_step.ts', 'export default 1');
    await write('app/b/steps/two_step.ts', 'export default 1');
    const gen = generator();
    stepsHook({ source: ['app/a/steps', 'app/b/steps'] })(undefined, undefined, gen);
    await gen.generate();

    const added = await write('app/b/steps/three_step.ts', 'export default 1');
    await gen.addFile(added);
    let barrel = await read('.adonisjs/durable/steps.ts');
    expect(barrel).toContain("'app/a/steps/one_step.ts'");
    expect(barrel).toContain("'app/b/steps/three_step.ts'");

    await gen.removeFile(join(appRoot, 'app/a/steps/one_step.ts'));
    barrel = await read('.adonisjs/durable/steps.ts');
    expect(barrel).not.toContain('one_step');
    expect(barrel).toContain("'app/b/steps/two_step.ts'");
    expect(barrel).toContain("'app/b/steps/three_step.ts'");
  });

  it('rejects an empty source list and an importAlias with several sources', () => {
    expect(() => workflowsHook({ source: [] })(undefined, undefined, generator())).toThrow(
      /at least one `source`/,
    );
    expect(() =>
      stepsHook({ source: ['app/a', 'app/b'], importAlias: '#x' })(
        undefined,
        undefined,
        generator(),
      ),
    ).toThrow(/importAlias/);
  });

  it('the provider boots from a generated multi-root barrel (workflows + steps)', async () => {
    await write(
      'app/orders/flows/pay_workflow.ts',
      `import { BaseWorkflow } from '${SRC}/base-workflow.js'
       export default class PayWorkflow extends BaseWorkflow {
         static workflow = { name: 'pay' }
         async run(ctx, input) { return ctx.step('charge', input) }
       }`,
    );
    await write(
      'app/billing/flows/refund_workflow.ts',
      `import { BaseWorkflow } from '${SRC}/base-workflow.js'
       export default class RefundWorkflow extends BaseWorkflow {
         static workflow = { name: 'refund' }
         async run(_ctx, input) { return 'refund:' + input }
       }`,
    );
    await write(
      'app/billing/steps/charge_step.ts',
      `import { defineStep } from '${SRC}/step-ref.js'
       export const charge = defineStep('charge', async (input) => 'charged:' + input)`,
    );
    const gen = generator();
    workflowsHook({ source: ['app/orders/flows', 'app/billing/flows'] })(undefined, undefined, gen);
    stepsHook({ source: ['app/orders/steps', 'app/billing/steps'] })(undefined, undefined, gen);
    await gen.generate();

    // The config points somewhere empty: registration can only come from the barrels.
    const config: DurableConfig = { workflowsPath: 'nowhere', stepsPath: 'nowhere' };
    let factory: (() => unknown) | undefined;
    let engine: WorkflowEngine | undefined;
    const app = {
      config: { get: (key: string, fallback?: unknown) => (key === 'durable' ? config : fallback) },
      getEnvironment: () => 'web',
      makePath: (...parts: string[]) => join(appRoot, ...parts),
      container: {
        singleton: (_key: unknown, f: () => unknown) => {
          factory = f;
        },
        make: async (key: unknown) => {
          if (key === WorkflowEngine) {
            engine ??= (await factory?.()) as WorkflowEngine;
            return engine;
          }
          return new (key as new () => unknown)();
        },
      },
    } as unknown as ApplicationService;
    const provider = new DurableProvider(app);
    provider.register();
    await provider.boot();

    await engine!.start('pay', '3', 'p1');
    const paid = await engine!.waitForRun('p1', { terminal: true, timeoutMs: 5000 });
    expect(paid.output).toBe('charged:3');
    await engine!.start('refund', '4', 'r1');
    expect((await engine!.waitForRun('r1')).output).toBe('refund:4');
    await provider.shutdown();
  });
});
